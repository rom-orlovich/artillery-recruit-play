let activeMapId = null;

export function setNpcMapId(id) {
  activeMapId = id || null;
}

export function normalizeChapterId(chapterId) {
  if (typeof chapterId === 'number' && Number.isFinite(chapterId)) {
    return CHAPTER_IDS[Math.max(0, Math.min(CHAPTER_IDS.length - 1, (chapterId | 0) - 1))] || 'ch1_bakum';
  }
  if (typeof chapterId === 'string') {
    if (CHAPTER_IDS.includes(chapterId)) return chapterId;
    const n = Number(chapterId);
    if (Number.isFinite(n) && n >= 1) return CHAPTER_IDS[Math.max(0, Math.min(CHAPTER_IDS.length - 1, (n | 0) - 1))];
  }
  return 'ch1_bakum';
}

export function regionOf(x, z) {
  if (activeMapId) return activeMapId;
  if (z > -128) return 'shivta';
  const [minX, maxX, minZ, maxZ] = REGIONS.yoav.rect;
  if (x >= minX && x <= maxX && z >= minZ && z <= maxZ && z > -215) return 'yoav';
  return 'line';
}

function isGuardSpawn(region, x, z) {
  if (region === 'shivta') return z < -35 && z > -42;
  if (region === 'yoav') return x > -56;
  if (region === 'zaura') return x > 55 && z > 30;
  if (region === 'beit_hillel') return x < -35 && z > 45;
  return LINE_GUARD_POSTS.some(([gx, gz]) => Math.hypot(x - gx, z - gz) < 4) || z < -380;
}

function isRangeSpawn(region, x, z) {
  return (region === 'shivta' && x > 45) || (region === 'kadita' && x < -10 && z > -5 && z < 12);
}

function isCommandSpawn(region, x, z) {
  return region === 'line' && ((x < -45 && z < -255 && z > -270) || (x > 14 && z < -238 && z > -250));
}

export function pickSpawnRole(region, x, z, crewOf, index) {
  if (crewOf !== null && crewOf !== undefined) return CREW_ROLE_CYCLE[index % CREW_ROLE_CYCLE.length];
  if (isGuardSpawn(region, x, z)) return 'ש.ג';
  if (isRangeSpawn(region, x, z)) return 'מטווח/רוכ"ש';
  if (isCommandSpawn(region, x, z)) return 'קשר';
  return CAMP_ROLE_CYCLE[index % CAMP_ROLE_CYCLE.length];
}

export function pickSpawnRank(role, index) {
  const cycle = role === 'מפקד צוות' ? COMMAND_RANK_CYCLE : ENLISTED_RANK_CYCLE;
  return cycle[index % cycle.length];
}

const nameState = {};
function ensureRegion(region) {
  if (!nameState[region]) nameState[region] = { used: new Set(), count: 0 };
  return nameState[region];
}

export function resetIdentityAssignments() {
  for (const key of Object.keys(nameState)) delete nameState[key];
}

export function seedNames(region, names) {
  const st = ensureRegion(region);
  for (const name of names) if (name) st.used.add(name);
}

export function isNameUsed(region, name) {
  return ensureRegion(region).used.has(name);
}

export function nextName(region) {
  const st = ensureRegion(region);
  let name = null;
  for (let i = 0; i < NAMES_POOL.length; i++) {
    const candidate = NAMES_POOL[(st.count + i) % NAMES_POOL.length];
    if (!st.used.has(candidate)) { name = candidate; st.count = st.count + i + 1; break; }
  }
  if (!name) name = `${NAMES_POOL[st.count % NAMES_POOL.length]}-${st.count}`;
  st.used.add(name);
  return name;
}

const OFFICER_ROLES = {
  rasar: 'מפקד צוות', masul: 'מפקד צוות', mefaketz: 'מפקד צוות',
  kasha: 'מטווח/רוכ"ש', apsanai: 'קשר', shekemist: 'קשר', outpost_cmd: 'מפקד צוות'
};

export function splitOfficerName(fullName) {
  const parts = String(fullName || '').split(' ');
  return { rank: parts.shift() || '', name: parts.join(' ') };
}

export const NAMED_OFFICERS = NPC_DEFS.map((def) => {
  const { rank, name } = splitOfficerName(def.name);
  return {
    id: def.id, name, rank, role: OFFICER_ROLES[def.id] || 'מפקד צוות',
    roleTitle: def.roleTitle, region: regionOf(def.pos.x, def.pos.z),
    pos: { x: def.pos.x, z: def.pos.z }, color: def.color, linesByChapter: def.linesByChapter
  };
});

export function seedOfficerNames() {
  for (const off of NAMED_OFFICERS) seedNames(off.region, [off.name]);
}

export function assignSpawnIdentity(spawn, index) {
  const region = regionOf(spawn.x, spawn.z);
  const role = pickSpawnRole(region, spawn.x, spawn.z, spawn.crewOf, index);
  return { name: nextName(region), rank: pickSpawnRank(role, index), role, region };
}

