function roleEntry(npc, chapterId) {
  const ch = normalizeChapterId(chapterId);
  const role = DIALOGUE_BY_ROLE[npc.role] || DIALOGUE_BY_ROLE['תותחן'];
  return role[ch] || role.ch1_bakum;
}

export function getDialogueLine(npc, chapterId) {
  const ch = normalizeChapterId(chapterId);
  if (npc.linesByChapter && npc.linesByChapter[ch]) return npc.linesByChapter[ch];
  return roleEntry(npc, ch).line;
}

export function getDialogueChoices(npc, chapterId) {
  return roleEntry(npc, chapterId).choices.map(([label, answer], i) => ({
    label, answer, tone: CHOICE_TONES[i % CHOICE_TONES.length]
  }));
}

export function getDialogueAnswer(npc, chapterId, index) {
  const choices = getDialogueChoices(npc, chapterId);
  const pick = choices[Math.max(0, Math.min(choices.length - 1, index | 0))];
  return pick ? pick.answer : null;
}

export function isOrderable(rank, playerRankId) {
  return (RANK_LEVELS[rank] ?? 0) < (RANK_ID_LEVELS[playerRankId] ?? 0);
}

